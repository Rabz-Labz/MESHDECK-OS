#!/usr/bin/env python3
"""embed_gif.py - put a GIF into the firmware as the CREDITS page logo.

Usage:
    python tools/embed_gif.py path/to/logo.gif

Rewrites core/ui/credits/credits_logo.cpp with the GIF's bytes, then rebuild the firmware (and
the simulator). Only the Python standard library is needed.

Checks made:
  - the file really is a GIF (GIF87a or GIF89a header). LVGL's decoder only accepts GIF89a, so a
    GIF87a header is rewritten as GIF89a (every GIF87a file is also valid GIF89a);
  - its size: LVGL decodes one frame at a time into width x height x 4 bytes, so very large logos
    use a lot of memory and animate slowly. Over 1200 x 220 px (the CREDITS page's logo area) or
    2 MB gets a warning.
"""
import os
import struct
import sys

OUT = os.path.join(os.path.dirname(__file__), "..", "core", "ui", "credits", "credits_logo.cpp")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    path = sys.argv[1]
    with open(path, "rb") as f:
        data = f.read()

    # Step 1: check it is a GIF and read its logical screen size (bytes 6-9, little-endian).
    if len(data) < 10 or data[:6] not in (b"GIF87a", b"GIF89a"):
        print(f"{path} is not a GIF file")
        return 1
    if data[:6] == b"GIF87a":
        data = b"GIF89a" + data[6:]
        print("GIF87a header rewritten as GIF89a (LVGL only reads GIF89a)")
    width, height = struct.unpack("<HH", data[6:10])
    print(f"{os.path.basename(path)}: {width} x {height} px, {len(data):,} bytes")
    if width > 1200 or height > 220:
        print("warning: over 1200 x 220 px; it won't fit the CREDITS page, so scale it down")
    if len(data) > 2 * 1024 * 1024:
        print("warning: over 2 MB; it will make the firmware much bigger")

    # Step 2: write it out as a C++ array, 20 bytes per line.
    lines = []
    for i in range(0, len(data), 20):
        lines.append(",".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    body = "\n".join(lines)
    src = (
        "// credits_logo.cpp - the CREDITS page logo as a byte array. Generated by tools/embed_gif.py;\n"
        f"// do not edit by hand. Source: {os.path.basename(path)}, {width} x {height} px.\n"
        '#include "ui/credits.h"\n\n'
        "namespace meshdeck {\n\n"
        "extern const unsigned char kCreditsLogoGif[] = {\n"
        f"{body}\n"
        "};\n"
        f"extern const unsigned int kCreditsLogoGifSize = {len(data)};\n\n"
        "} // namespace meshdeck\n"
    )
    with open(OUT, "w", newline="\n") as f:
        f.write(src)
    print(f"wrote {os.path.normpath(OUT)}; rebuild the firmware to include it")
    return 0


if __name__ == "__main__":
    sys.exit(main())
